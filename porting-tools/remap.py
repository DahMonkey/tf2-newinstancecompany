STRING_RE = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])\'')
COMMENT_RE = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)

def split_code(src):
    """Yield (is_code, text) chunks so renames skip strings and comments."""
    pos = 0
    pat = re.compile(r'"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])+\'|//[^\n]*|/\*.*?\*/', re.S)
    for m in pat.finditer(src):
        if m.start() > pos:
            yield True, src[pos:m.start()]
        yield False, m.group(0)
        pos = m.end()
    if pos < len(src):
        yield True, src[pos:]

def remap_code(code):
    # strip fully-qualified 1.12 class references down to the simple name
    code = re.sub(r"\bnet\.minecraft(?:forge)?(?:\.[a-z0-9_]+)+\.([A-Z]\w*)", r"\1", code)
    # class names
    for old, new in SIMPLE:
        if old == new:
            continue
        code = re.sub(r"(?<![\w.])" + old + r"\b", new, code)
        # qualified nested references like EntityPlayer.SleepResult keep working via simple name
    for pat, rep in M:
        code = re.sub(pat, rep, code)
    return code

def process(src):
    lines = src.split("\n")
    pkg = ""
    kept_imports, body = [], []
    for line in lines:
        s = line.strip()
        if s.startswith("package "):
            pkg = line
            continue
        if s.startswith("import "):
            name = s[len("import "):].rstrip(";").strip()
            if name.startswith("static "):
                if "net.minecraft" in name:
                    continue
                kept_imports.append(line)
                continue
            if name.startswith(("net.minecraft", "org.lwjgl", "com.google.common.base.Predicate",
                                "com.google.common.base.Optional", "mezz.jei", "atomicstryker", "cofh",
                                "org.spongepowered", "net.minecraftforge")):
                continue
            kept_imports.append(line)
            continue
        body.append(line)
    text = "\n".join(body)
    text = "".join(remap_code(t) if code else t for code, t in split_code(text))
    # guava Predicate/Optional -> java.util.function / java.util
    used = set(re.findall(r"\b[A-Z][A-Za-z0-9_]*\b", "".join(t for c, t in split_code(text) if c)))
    imports = sorted({NEW_IMPORTS[u] for u in used if u in NEW_IMPORTS})
    if "Predicate" in used:
        imports.append("java.util.function.Predicate")
    if "TF2Util" in used and "rafradek.TF2weapons.util.TF2Util" not in src and not pkg.strip().endswith("util;"):
        imports.append("rafradek.TF2weapons.util.TF2Util")
    out = [pkg, ""]
    out += kept_imports
    out += ["import %s;" % i for i in imports]
    out.append("")
    out.append(text.lstrip("\n"))
    return "\n".join(out)

def main():
    src_root, out_root = sys.argv[1], sys.argv[2]
    n = 0
    for root, _, files in os.walk(src_root):
        for f in files:
            if not f.endswith(".java"):
                continue
            p = os.path.join(root, f)
            rel = os.path.relpath(p, src_root)
            with open(p, encoding="utf-8", errors="replace") as fh:
                src = fh.read().replace("\r\n", "\n")
            out = os.path.join(out_root, rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with open(out, "w", encoding="utf-8") as fh:
                fh.write(process(src))
            n += 1
    print("remapped", n, "files")

if __name__ == "__main__":
    main()
